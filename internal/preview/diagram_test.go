func TestRT019_1_DiagramBlocksRenderAsPNG(t *testing.T) {
	root := t.TempDir()
	doc := "```mermaid\ngraph TD\nA-->B\n```\n\n```plantuml\n@startuml\nAlice -> Bob\n@enduml\n```\n"
	r := run(t, root, []string{"PREVIEW_TEST_FAULT=diagram-renderers"}, source(t, root, "diagrams.md", doc))
	success(t, r, 1)
	page := documentNode(t, r.pages[0], "hp-document")
	if got := len(nodes(page, "img")); got != 2 {
		t.Fatalf("rendered diagram count=%d, expected 2", got)
	}
	if text := textOf(page); !strings.Contains(text, "graph TD") || !strings.Contains(text, "@startuml") {
		t.Fatal("diagram rendering removed literal source fallback")
	}
}

func TestRT019_1_ServiceDiagramsUseDistinctMedia(t *testing.T) {
	host := NativeHost()
	actual := host.Execute
	host.LookPath = func(name string) (string, error) { return "/tools/" + name, nil }
	ordinal := byte(0)
	host.Execute = func(ctx context.Context, command Command) ([]byte, error) {
		if base := filepath.Base(command.Path); base == "mmdc" || base == "plantuml" {
			ordinal++
			return append(rasterFixtureForChild(), ordinal), nil
		}
		return actual(ctx, command)
	}
	var diagnostics bytes.Buffer
	service := startObservedTestService(t, host, &diagnostics)
	doc := "```mermaid\ngraph TD\nA-->B\n```\n\n```plantuml\n@startuml\nA -> B\n@enduml\n```\n"
	target := service.register(t, "diagrams.md", doc)
	status, _, page := responseAsset(t, service, http.MethodGet, target)
	images := nodes(parseHTTPDocument(t, page), "img")
	if status != http.StatusOK || len(images) != 2 || attr(images[0], "src") == attr(images[1], "src") {
		t.Fatalf("service diagrams status=%d count=%d urls=%q/%q diagnostics=%s", status, len(images), func() string {
			if len(images) > 0 {
				return attr(images[0], "src")
			}
			return ""
		}(), func() string {
			if len(images) > 1 {
				return attr(images[1], "src")
			}
			return ""
		}(), diagnostics.String())
	}
	var delivered [][]byte
	for _, image := range images {
		status, headers, data := responseAsset(t, service, http.MethodGet, attr(image, "src"))
		if status != http.StatusOK || headers.Get("Content-Type") != "image/png" || rasterMIME(data) != "image/png" {
			t.Fatal("service diagram route returned the wrong PNG")
		}
		delivered = append(delivered, data)
	}
	if bytes.Equal(delivered[0], delivered[1]) {
		t.Fatal("distinct diagram routes returned the same generated bytes")
	}
}

func TestRT019_1_DiagramRendererSecurityAndBounds(t *testing.T) {
	var command Command
	host := NativeHost()
	host.LookPath = func(name string) (string, error) { return "/tools/" + name, nil }
	host.Execute = func(_ context.Context, got Command) ([]byte, error) {
		command = got
		return rasterFixtureForChild(), nil
	}
	s := &session{path: t.TempDir(), host: host, cfg: config{outputBytes: maxAssetBytes}, log: &console{}}
	p := &page{}
	if err := s.extract(); err != nil {
		t.Fatal(err)
	}
	if _, err := s.renderDiagram(t.Context(), p, "plantuml", "@startuml\nA -> B\n@enduml"); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(strings.Join(command.Env, " "), "PLANTUML_SECURITY_PROFILE=SANDBOX") || command.Dir != s.path {
		t.Fatal("PlantUML did not run in its closed security profile and private session")
	}
	if _, err := s.renderDiagram(t.Context(), p, "mermaid", "graph TD\nA-->B"); err != nil {
		t.Fatal(err)
	}
	configPath := filepath.Join(s.path, "mermaid.json")
	configData, err := os.ReadFile(configPath)
	if err != nil || !strings.Contains(string(configData), `"securityLevel": "strict"`) || !strings.Contains(strings.Join(command.Args, " "), configPath) {
		t.Fatal("Mermaid did not receive the owned strict configuration")
	}
	if _, err := s.renderDiagram(t.Context(), p, "mermaid", strings.Repeat("x", maxDiagramSource+1)); err == nil {
		t.Fatal("oversized Mermaid source was accepted")
	}
}
